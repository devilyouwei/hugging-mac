"""Human-safe, front-facing COCO-17 pose templates."""

from dataclasses import dataclass


@dataclass(frozen=True)
class PoseTemplate:
    template_id: str
    name: str
    cue: str
    difficulty: int
    points: tuple[tuple[float, float], ...]
    required_keypoints: tuple[int, ...]


# COCO order: nose, eyes, ears, shoulders, elbows, wrists, hips, knees, ankles.
BASE = (
    (0.50, 0.12),
    (0.48, 0.10),
    (0.52, 0.10),
    (0.45, 0.11),
    (0.55, 0.11),
    (0.40, 0.28),
    (0.60, 0.28),
    (0.34, 0.44),
    (0.66, 0.44),
    (0.30, 0.60),
    (0.70, 0.60),
    (0.44, 0.56),
    (0.56, 0.56),
    (0.42, 0.76),
    (0.58, 0.76),
    (0.40, 0.96),
    (0.60, 0.96),
)
BODY = tuple(range(5, 17))


def _pose(
    template_id: str,
    name: str,
    cue: str,
    difficulty: int,
    changes: dict[int, tuple[float, float]],
    required: tuple[int, ...] = BODY,
) -> PoseTemplate:
    points = list(BASE)
    for index, point in changes.items():
        points[index] = point
    return PoseTemplate(template_id, name, cue, difficulty, tuple(points), required)


